root = pathlib.Path(__file__).resolve().parent.parent
for i, lang in enumerate(("en", "fr")):
    data = {}
    for key, pair in M.items():
        text = pair[i]
        if "$" in text.replace("$1", "").replace("$2", "").replace("$3", ""):
            raise SystemExit(f"« $ » littéral non échappé dans {key}")
        data[key] = {"message": text}
    out = root / "_locales" / lang / "messages.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{out.relative_to(root)} : {len(data)} messages")
